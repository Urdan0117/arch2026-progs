#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "rubik_tables.h"

enum { NP = 5040, NO = 729, N = NP * NO, MAXD = 5 };

static uint8_t dist[N];       /* 0xFF = 還沒走到 */
static uint32_t queue[20000]; /* 狀態編號 p * 729 + o */
static uint16_t start[NP + 1];
static uint16_t entry[20000];

/* 印成 .half 或 .byte，一行 16 個 */
static void emit(const char *label, const void *v, int n, int half)
{
    printf("    .globl  %s\n%s:\n", label, label);
    for (int i = 0; i < n; ++i)
        printf("%s%u%s",
               i % 16 ? ", " : (half ? "    .half   " : "    .byte   "),
               (unsigned) (half ? ((const uint16_t *) v)[i]
                                : ((const uint8_t *) v)[i]),
               i % 16 == 15 || i == n - 1 ? "\n" : "");
}

int main(void)
{
    /* 1. BFS：從已解開始，只走到 5 步 */
    memset(dist, 0xFF, sizeof dist);
    dist[0] = 0;
    int head = 0, tail = 0;
    queue[tail++] = 0;
    while (head < tail) {
        uint32_t s = queue[head++];
        if (dist[s] == MAXD) /* (a) 已經 5 步了，不再往外 */
            continue;
        uint32_t p = s / NO, o = s % NO; /* host 上可以用除法 */
        for (int f = 0; f < 3; ++f) {
            uint32_t np = p, no = o;
            for (int t = 0; t < 3; ++t) {
                np = perm_move[f][np];
                no = orient_move[f][no];
                uint32_t n = np * NO + no;
                if (dist[n] == 0xFF) {
                    dist[n] = dist[s] + 1;
                    queue[tail++] = n;
                }
            }
        }
    }

    /* 2. 分桶：p 由小到大，同一個 p 裡 o 由小到大 */
    int k = 0;
    for (uint32_t p = 0; p < NP; ++p) {
        start[p] = (uint16_t) k;
        for (uint32_t o = 0; o < NO; ++o)
            if (dist[p * NO + o] != 0xFF)
                entry[k++] = (uint16_t) ((o << 3) | dist[p * NO + o]);
    }
    start[NP] = (uint16_t) k;
    fprintf(stderr, "%d states within %d moves\n", k, MAXD);

    /* 3. 印出 */
    printf("# Generated by tools/gen_rubik_tables.c; do not edit by hand.\n");
    printf("    .section .rodata\n    .balign 2\n");
    emit("rk_perm_move", perm_move, 3 * NP, 1);
    emit("rk_orient_move", orient_move, 3 * NO, 1);
    emit("rk_bucket_start", start, NP + 1, 1);
    emit("rk_bucket_entry", entry, k, 1);
    emit("rk_perm_pdb", perm_pdb, NP, 0);
    emit("rk_orient_pdb", orient_pdb, NO, 0);
    return 0;
}